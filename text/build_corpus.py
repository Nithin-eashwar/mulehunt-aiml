"""Build data/raw/scam_messages/messages.csv from three honestly labelled sources.

    python -m text.build_corpus

- source = public:    UCI SMS Spam Collection (Almeida & Hidalgo 2011, CC BY 4.0), real SMS;
                      ham -> genuine, spam -> scam / other_scam. Not Indian.
- source = reported:  messages we wrote from scam patterns described in cited public
                      reports (public/reported_patterns.csv, one source URL per row).
- source = synthetic: generated by text.synthetic from seeded templates.

Every text is passed through the anonymiser so placeholders are consistent across sources.
"""

import csv
from pathlib import Path

import pandas as pd

from text.anonymise import anonymise
from text.dataset import COLUMNS, MESSAGES, normalise, validate_messages

PUBLIC = Path("data/raw/scam_messages/public")
UCI = PUBLIC / "uci_sms_spam_collection.tsv"
REPORTED = PUBLIC / "reported_patterns.csv"
SYNTHETIC = PUBLIC / "synthetic_messages.csv"


def _uci() -> pd.DataFrame:
    rows = []
    with open(UCI, encoding="utf-8", errors="replace") as f:
        for i, line in enumerate(f, 1):
            label, _, text = line.rstrip("\n").partition("\t")
            spam = label == "spam"
            rows.append({"msg_id": f"UCI{i:05d}", "text": text, "label": "scam" if spam else "genuine",
                         "scam_type": "other_scam" if spam else "genuine", "language": "english",
                         "channel": "sms", "source": "public"})
    return pd.DataFrame(rows)


def _ours(path: Path, source: str) -> pd.DataFrame:
    df = pd.read_csv(path, dtype=str, keep_default_na=False)
    return pd.DataFrame({"msg_id": df.ref_id, "text": df.text,
                         "label": ["genuine" if t == "genuine" else "scam" for t in df.scam_type],
                         "scam_type": df.scam_type, "language": df.language, "channel": df.channel,
                         "source": source})


def build(out=MESSAGES) -> pd.DataFrame:
    if not SYNTHETIC.exists():
        from text.synthetic import main as synth
        synth([])
    df = pd.concat([_uci(), _ours(REPORTED, "reported"), _ours(SYNTHETIC, "synthetic")], ignore_index=True)
    df["text"] = [anonymise(t)[0].strip() for t in df.text]
    df = df[df.text.str.len() > 0]
    df = df.loc[~df.text.map(normalise).duplicated()].reset_index(drop=True)[COLUMNS]
    errors = validate_messages(df)
    if errors:
        raise ValueError("; ".join(errors))
    df.to_csv(out, index=False, lineterminator="\n", quoting=csv.QUOTE_MINIMAL)
    print(f"wrote {out}: {len(df)} messages")
    print(df.groupby(["source", "label"]).size().to_string())
    return df


if __name__ == "__main__":
    build()
